class Table:
    def __init__(self, rows: list[dict[str, object]]):
        self.rows = rows


class Database:
    def __init__(self, path: Path):
        self.data = path.read_bytes()
        meta_path = path.with_name(path.stem + "-meta.xml")
        self.meta = ET.parse(meta_path).getroot()
        self.tables: dict[str, ET.Element] = {
            t.attrib["shortname"]: t for t in self.meta.findall("table")
        }
        count = struct.unpack_from("<I", self.data, 0x10)[0]
        self.base = 0x20 + count * 8
        self.offsets: list[tuple[int, ET.Element]] = []
        for i in range(count):
            entry = 0x20 + i * 8
            shortname = self.data[entry : entry + 4].decode("latin1", "replace")
            offset = struct.unpack_from("<I", self.data, entry + 4)[0]
            table = self.tables.get(shortname)
            if table is not None:
                self.offsets.append((offset, table))
        self.offsets.sort(key=lambda item: item[0])

    def read(self, name: str) -> Table:
        for index, (offset, table) in enumerate(self.offsets):
            if table.attrib["name"] != name:
                continue
            start = self.base + offset
            end = self.base + (
                self.offsets[index + 1][0]
                if index + 1 < len(self.offsets)
                else len(self.data) - self.base
            )
            field_count = struct.unpack_from("<I", self.data, start + 0x14)[0]
            names = {
                f.attrib["shortname"]: f.attrib["name"]
                for f in table.findall("./fields/field")
            }
            descriptors: dict[str, tuple[int, int]] = {}
            for i in range(field_count):
                pos = start + 0x20 + i * 16
                _, bit_offset = struct.unpack_from("<II", self.data, pos)
                shortname = self.data[pos + 8 : pos + 12].decode("latin1", "replace")
                width = struct.unpack_from("<I", self.data, pos + 12)[0]
                descriptors[names[shortname]] = (bit_offset, width)
            max_bits = max(offset + width for offset, width in descriptors.values())
            stride = ((max_bits + 7) // 8 + 3) // 4 * 4
            header = 0x20 + field_count * 16
            row_count = (end - start - header) // stride
            blob = self.data[start + header : end]
            rows = []
            for r in range(row_count):
                rows.append(
                    {
                        "raw": blob[r * stride : (r + 1) * stride],
                        "descriptors": descriptors,
                    }
                )
            return Table(rows)


def value(row: dict[str, object], field: str) -> int:
    offset, width = row["descriptors"][field]  # type: ignore[index]
    raw = row["raw"]
    bits = 0
    for i in range(width):
        bit = offset + i
        bits |= ((raw[bit >> 3] >> (bit & 7)) & 1) << i
    return bits


def text(row: dict[str, object], field: str) -> str:
    offset, width = row["descriptors"][field]  # type: ignore[index]
    raw = row["raw"]
    bits = 0
    for i in range(width):
        bit = offset + i
        bits |= ((raw[bit >> 3] >> (bit & 7)) & 1) << i
    return bits.to_bytes(width // 8, "little").split(b"\x00")[0].decode("utf-8", "replace").strip()


def slugify(name: str, team_id: int) -> str:
    cleaned = []
    for char in name.lower():
        if char.isalnum():
            cleaned.append(char)
        elif char in " -_/.":
            cleaned.append("-")
    slug = "".join(cleaned).strip("-")
    while "--" in slug:
        slug = slug.replace("--", "-")
    return f"{slug}-{team_id}" if slug else f"club-{team_id}"


def nation_for(name: str) -> tuple[str, str]:
    if name in NATIONS:
        return NATIONS[name]
    letters = "".join(c for c in name.upper() if c.isalpha())
    return (letters[:3] or "UNK", "🏳️")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--today", default="2026-10-25")
    args = parser.parse_args()

    today = date.fromisoformat(args.today)
    db = Database(DB_DIR / "fifa_ng_db.db")

    teams = db.read("teams")
    team_rows: dict[int, dict[str, object]] = {}
    team_name: dict[int, str] = {}
    team_rating: dict[int, int] = {}
    team_gender: dict[int, int] = {}
    for row in teams.rows:
        team_id = value(row, "teamid")
        name = text(row, "teamname")
        if not name:
            continue
        team_rows[team_id] = row
        team_name[team_id] = name
        team_rating[team_id] = value(row, "overallrating")
        team_gender[team_id] = value(row, "gender")

    leagues = db.read("leagues")
    league_name = {
        value(row, "leagueid"): text(row, "leaguename") for row in leagues.rows
    }
    links = db.read("leagueteamlinks")
    team_league: dict[int, str] = {}
    team_league_id: dict[int, int] = {}
    for row in links.rows:
        league_id = value(row, "leagueid")
        team_id = value(row, "teamid")
        if team_id in team_league:
            continue
        if league_id in league_name:
            team_league[team_id] = league_name[league_id]
            team_league_id[team_id] = league_id

    # The career is a men's Champions League: women's sides and national teams would put
    # a parallel set of squads and duplicate people into the same market.
    national_team_league_ids = {79}

    excluded = {
        team_id
        for team_id, name in team_name.items()
        if any(pattern in name.lower() for pattern in EXCLUDED_TEAM_PATTERNS)
        or team_gender.get(team_id, 0) == 1
        or team_league_id.get(team_id) in national_team_league_ids
    }

    nations_table = db.read("nations")
    player_link = db.read("teamplayerlinks")
    players = db.read("players")
    squad_of: dict[int, int] = {}
    for row in player_link.rows:
        player_id = value(row, "playerid")
        team_id = value(row, "teamid")
        if player_id in squad_of:
            # Prefer a real club over a side that is being ignored.
            if squad_of[player_id] in excluded and team_id not in excluded:
                squad_of[player_id] = team_id
            continue
        squad_of[player_id] = team_id

    club_index: dict[int, str] = {}
    for team_id, name in team_name.items():
        if team_id in excluded:
            continue
        club_index[team_id] = slugify(name, team_id)

    # The clubs the app's Champions League plays with keep their existing ids, so saves,
    # colours and the fixture engine keep working.
    competition_team_ids: dict[str, int] = {}
    for app_id, db_name in UCL_CLUBS.items():
        if not db_name:
            continue
        team_id = next(
            (
                tid
                for tid, nm in team_name.items()
                if nm == db_name and tid not in excluded and tid in club_index
            ),
            None,
        )
        if team_id is None:
            continue
        competition_team_ids[app_id] = team_id
        club_index[team_id] = app_id

    records = []
    skipped_no_club = 0
    skipped_youth = 0
    for row in players.rows:
        player_id = value(row, "playerid")
        team_id = squad_of.get(player_id)
        if team_id is None or team_id not in club_index:
            skipped_no_club += 1
            continue
        overall = value(row, "overallrating")
        if overall <= 0:
            skipped_youth += 1
            continue
        birth = value(row, "birthdate")
        born = DATE_EPOCH + timedelta(days=birth)
        age = today.year - born.year - ((today.month, today.day) < (born.month, born.day))
        age = max(15, min(45, age))
        records.append(
            {
                "id": player_id,
                "team": team_id,
                "ovr": overall,
                "pot": max(overall, value(row, "potential")),
                "pos": POSITIONS.get(value(row, "preferredposition1"), "centralMid"),
                "nat": value(row, "nationality"),
                "age": age,
                "name": None,
            }
        )

    nations_rows = {}
    for row in nations_table.rows:
        nations_rows[value(row, "nationid")] = text(row, "nationname")
    for record in records:
        name = nations_rows.get(record["nat"], "")
        code, flag = nation_for(name)
        record["nat"] = code
        record["natFlag"] = flag
        record["natName"] = name

    players_per_club = Counter(r["team"] for r in records)
    clubs = []
    for team_id, name in sorted(team_name.items(), key=lambda item: item[1]):
        if team_id in excluded or team_id not in club_index:
            continue
        if players_per_club.get(team_id, 0) == 0:
            continue
        clubs.append(
            {
                "id": club_index[team_id],
                "name": name,
                "rating": team_rating.get(team_id, 0),
                "league": team_league.get(team_id),
                "teamID": team_id,
                "competition": team_id in competition_team_ids.values(),
            }
        )

    by_team = defaultdict(list)
    for record in records:
        by_team[record["team"]].append(record)

    ucl = []
    for app_id in UCL_CLUBS:
        team_id = competition_team_ids.get(app_id)
        if team_id is None:
            ucl.append({"id": app_id, "club": None, "teamID": None, "count": 0, "rating": None, "top": None})
            continue
        squad = sorted(by_team.get(team_id, []), key=lambda r: -r["ovr"])
        ucl.append(
            {
                "id": app_id,
                "club": club_index[team_id],
                "teamID": team_id,
                "count": len(squad),
                "rating": team_rating.get(team_id),
                "top": [(r["id"], r["ovr"], r["pos"], r["nat"], r["age"]) for r in squad[:5]],
            }
        )

    payload = {
        "source": "db_loc_27/data/db/fifa_ng_db.db",
        "generatedFor": args.today,
        "clubs": clubs,
        "players": [
            {
                "id": r["id"],
                "ovr": r["ovr"],
                "pot": r["pot"],
                "pos": r["pos"],
                "nat": r["nat"],
                "age": r["age"],
                "club": club_index[r["team"]],
                "name": r["name"],
            }
            for r in records
        ],
        "nations": [
            {"code": code, "name": name, "flag": flag}
            for name, (code, flag) in sorted(NATIONS.items())
        ],
    }

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, ensure_ascii=False, separators=(",", ":")))

    print(f"wrote {out} ({out.stat().st_size / 1_048_576:.2f} MB)")
    print(f"clubs {len(clubs)}  players {len(records)}  clubs with squads {len(by_team)}")
    print(f"skipped: no club {skipped_no_club}, no overall {skipped_youth}")
    for entry in ucl:
        print(
            f"  UCL {entry['id']:<22} {str(entry['club']):<28} rating={entry['rating']} squad={entry['count']} top={entry['top']}"
        )
    rated = Counter(r["ovr"] // 10 * 10 for r in records)
    print("overall buckets", sorted(rated.items()))
    ages = sorted(r["age"] for r in records)
    print("age p5/p50/p95", ages[len(ages) // 20], ages[len(ages) // 2], ages[-len(ages) // 20])
    return 0


if __name__ == "__main__":
    sys.exit(main())
