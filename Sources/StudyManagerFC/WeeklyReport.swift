import AppKit
import SwiftUI
import UniformTypeIdentifiers

/// A one-page summary of the last seven days, built from what is already recorded, and
/// written out as Markdown so it can be read, printed or handed to a tutor.
enum WeeklyReport {
    static func markdown(state: GameState, now: Date = Date(), calendar: Calendar = .current) -> String {
        let start = calendar.date(byAdding: .day, value: -7, to: calendar.startOfDay(for: now)) ?? now
        let sessions = state.recentSessions.filter { $0.date >= start }

        var lines: [String] = []
        lines.append("# Study Manager FC — weekly report")
        lines.append("")
        lines.append("Week ending \(now.formatted(.dateTime.day().month(.wide).year())).")
        lines.append("")

        let minutes = sessions.reduce(0) { $0 + $1.minutes }
        lines.append("## Totals")
        lines.append("")
        lines.append("- Sessions: \(sessions.count)")
        lines.append("- Minutes studied: \(minutes)")
        lines.append("- Active days: \(Set(sessions.map { calendar.startOfDay(for: $0.date) }).count)")
        lines.append("")

        let bySubject = Dictionary(grouping: sessions) { $0.subject ?? .other }
        if !bySubject.isEmpty {
            lines.append("## Minutes by subject")
            lines.append("")
            for subject in bySubject.keys.sorted(by: { $0.shortName < $1.shortName }) {
                let subjectMinutes = (bySubject[subject] ?? []).reduce(0) { $0 + $1.minutes }
                lines.append("- \(subject.shortName): \(subjectMinutes)")
            }
            lines.append("")
        }

        let marked = sessions.filter { ($0.marksTotal ?? 0) > 0 }
        if !marked.isEmpty {
            let obtained = marked.reduce(0) { $0 + ($1.marksObtained ?? 0) }
            let total = marked.reduce(0) { $0 + ($1.marksTotal ?? 0) }
            let percentage = total > 0 ? Int((Double(obtained) / Double(total) * 100).rounded()) : 0
            lines.append("## Marked work")
            lines.append("")
            lines.append("- Pieces marked: \(marked.count)")
            lines.append("- Marks: \(obtained)/\(total) (\(percentage)%)")
            lines.append("")
        }

        let resolved = state.mistakes.filter { entry in
            entry.isResolved && (entry.lastReviewed ?? entry.date) >= start
        }
        let added = state.mistakes.filter { $0.date >= start }
        if !added.isEmpty || !resolved.isEmpty {
            lines.append("## Bulletproof Journal")
            lines.append("")
            lines.append("- Mistakes logged: \(added.count)")
            lines.append("- Mistakes beaten: \(resolved.count)")
            let causes = Dictionary(grouping: state.mistakes.filter { !$0.isResolved }) { $0.cause ?? .unclassified }
            let top = causes.sorted { $0.value.count > $1.value.count }.prefix(3)
            if !top.isEmpty {
                lines.append("- Biggest open causes: " + top.map { "\($0.key.title) (\($0.value.count))" }.joined(separator: ", "))
            }
            lines.append("")
        }

        let projections = GradeProjection.all(from: state.assessments)
        if !projections.isEmpty {
            lines.append("## Grade projection")
            lines.append("")
            for projection in projections {
                lines.append("- \(projection.subject.shortName): \(Int(projection.average.rounded()))% so far, \(projection.satWeighting)% weight assessed")
            }
            lines.append("")
        }

        let plan = StudyPlan.week(for: state, sessions: state.recentSessions, from: now, calendar: calendar)
        if !plan.isEmpty {
            lines.append("## Next week's focus")
            lines.append("")
            for item in plan.prefix(5) {
                lines.append("- \(item.day.formatted(.dateTime.weekday(.wide))): \(item.topic) — \(item.minutes) min (\(item.reason))")
            }
            lines.append("")
        }

        lines.append("---")
        lines.append("Generated by Study Manager FC.")
        return lines.joined(separator: "\n")
    }

    /// Opens a save panel and writes the Markdown, returning the URL when it was written.
    @MainActor
    @discardableResult
    static func export(state: GameState) -> URL? {
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd"
        let panel = NSSavePanel()
        panel.nameFieldStringValue = "Study-Report-\(formatter.string(from: Date())).md"
        panel.allowedContentTypes = [UTType(filenameExtension: "md") ?? .plainText]
        panel.canCreateDirectories = true
        guard panel.runModal() == .OK, let url = panel.url else { return nil }
        do {
            try markdown(state: state).write(to: url, atomically: true, encoding: .utf8)
            return url
        } catch {
            return nil
        }
    }
}

/// The dashboard's export card: one button, one file, no settings.
struct WeeklyReportCard: View {
    @Environment(AppStore.self) private var store
    @State private var exportMessage: String?

    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            SectionHeader(
                title: "Weekly report",
                subtitle: "Sessions, minutes, marks, mistakes beaten and next week's focus — as Markdown",
                symbol: "doc.text"
            )
            HStack(spacing: 8) {
                Button("Export this week") {
                    if WeeklyReport.export(state: store.state) != nil {
                        exportMessage = "Saved."
                    } else {
                        exportMessage = "Cancelled."
                    }
                }
                .buttonStyle(.bentoProminent)
                .bentoTint(.primary)
                Button("Copy to clipboard") {
                    let text = WeeklyReport.markdown(state: store.state)
                    NSPasteboard.general.clearContents()
                    NSPasteboard.general.setString(text, forType: .string)
                    exportMessage = "Copied."
                }
                .buttonStyle(.bentoBordered)
                .bentoTint(.secondary)
                Spacer(minLength: 0)
                if let exportMessage {
                    Text(exportMessage)
                        .font(.system(size: 9, weight: .semibold))
                        .foregroundStyle(.secondary)
                }
            }
        }
        .padding(16)
        .background(
            RoundedRectangle(cornerRadius: 18, style: .continuous)
                .fill(Neon.panel.opacity(0.55))
        )
        .overlay(
            RoundedRectangle(cornerRadius: 18, style: .continuous)
                .stroke(Neon.border, lineWidth: 1)
        )
    }
}
