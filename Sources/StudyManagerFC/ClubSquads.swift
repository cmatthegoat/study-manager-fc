    static func starters(for clubID: String) -> [StarterSeed] {
        all[clubID] ?? []
    }

    static func averageRating(for clubID: String) -> Double {
        let starters = starters(for: clubID)
        guard !starters.isEmpty else { return 0 }
        let total = starters.reduce(0) { $0 + $1.rating }
        return Double(total) / Double(starters.count)
    }

    static func roundedRating(for clubID: String) -> Int {
        Int(averageRating(for: clubID).rounded())
    }
