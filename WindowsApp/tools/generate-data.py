#!/usr/bin/env python3
"""Generates C# game data from the macOS Swift sources so both apps share one dataset."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS = (ROOT / "Sources/StudyManagerFC/Models.swift").read_text()
SQUADS = (ROOT / "Sources/StudyManagerFC/ClubSquads.swift").read_text()
FACTORY = (ROOT / "Sources/StudyManagerFC/PlayerFactory.swift").read_text()
OUT = ROOT / "WindowsApp/src/StudyManagerFC.Core/Data.Generated.cs"

POSITIONS = {
    "goalkeeper": "Goalkeeper",
    "leftBack": "LeftBack",
    "centerBack": "CenterBack",
    "rightBack": "RightBack",
    "defensiveMid": "DefensiveMid",
    "centralMid": "CentralMid",
    "attackingMid": "AttackingMid",
    "leftWing": "LeftWing",
    "striker": "Striker",
    "rightWing": "RightWing",
}


def cs(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


nations = re.findall(r'Nation\(code: "([^"]+)", name: "([^"]+)", flag: "([^"]+)"\)', MODELS)
clubs = re.findall(
    r'Club\(id: "([^"]+)", name: "([^"]+)", shortName: "([^"]+)", code: "([^"]+)", '
    r'countryCode: "([^"]+)", primaryHex: "([^"]+)", secondaryHex: "([^"]+)", '
    r'rating: ClubSquads\.roundedRating\(for: "([^"]+)"\)\)',
    MODELS,
)

squads = {}
for club_id, body in re.findall(r'\n        "([a-z0-9-]+)": \[\n(.*?)\n        \],', SQUADS, re.DOTALL):
    seeds = re.findall(
        r'StarterSeed\(name: "([^"]+)", rating: (\d+), position: \.(\w+), nationCode: "([^"]+)"\)', body
    )
    squads[club_id] = seeds
    if not seeds:
        raise SystemExit(f"no seeds parsed for {club_id}")

pools = {}
for code, first_body, last_body in re.findall(
    r'"([A-Z]{3})": NamePool\(first: \[(.*?)\], last: \[(.*?)\]\)', FACTORY, re.DOTALL
):
    pools[code] = (re.findall(r'"([^"]*)"', first_body), re.findall(r'"([^"]*)"', last_body))

fallback_match = re.search(
    r"static let fallback = NamePool\(\s*first: \[(.*?)\],\s*last: \[(.*?)\]\s*\)", FACTORY, re.DOTALL
)
if not fallback_match:
    raise SystemExit("fallback name pool not found")
fallback = (
    re.findall(r'"([^"]*)"', fallback_match.group(1)),
    re.findall(r'"([^"]*)"', fallback_match.group(2)),
)

if len(nations) != 27:
    raise SystemExit(f"expected 27 nations, found {len(nations)}")
if len(clubs) != 36:
    raise SystemExit(f"expected 36 clubs, found {len(clubs)}")
if len(squads) != 36:
    raise SystemExit(f"expected 36 squads, found {len(squads)}")
if len(pools) != 27:
    raise SystemExit(f"expected 27 name pools, found {len(pools)}")

rating = {}
for club_id, seeds in squads.items():
    total = sum(int(seed[1]) for seed in seeds)
    rating[club_id] = int(total / len(seeds) + 0.5)

lines = [
    "// <auto-generated>",
    "// Generated from Sources/StudyManagerFC by WindowsApp/tools/generate-data.py.",
    "// Do not hand-edit; both apps read the same dataset.",
    "// </auto-generated>",
    "#nullable enable",
    "namespace StudyManagerFC.Core;",
    "",
    "public sealed record Nation(string Code, string Name, string Flag)",
    "{",
    "    public string Id => Code;",
    "}",
    "",
    "public static class Nations",
    "{",
    "    public static readonly Nation[] All =",
    "    [",
]
for code, name, flag in nations:
    lines.append(f"        new({cs(code)}, {cs(name)}, {cs(flag)}),")
lines += [
    "    ];",
    "",
    "    public static Nation For(string code) =>",
    "        Array.Find(All, nation => nation.Code == code) ?? All[0];",
    "}",
    "",
    "public static class ClubSquads",
    "{",
    "    public static readonly Dictionary<string, StarterSeed[]> All = new()",
    "    {",
]
for club in clubs:
    club_id = club[0]
    seeds = squads[club_id]
    lines.append(f"        [{cs(club_id)}] =")
    lines.append("        [")
    for name, seed_rating, position, nation in seeds:
        lines.append(
            f"            new({cs(name)}, {seed_rating}, PlayerPosition.{POSITIONS[position]}, {cs(nation)}),"
        )
    lines.append("        ],")
lines += [
    "    };",
    "",
    "    public static StarterSeed[] StartersFor(string clubId) =>",
    "        All.TryGetValue(clubId, out var seeds) ? seeds : Array.Empty<StarterSeed>();",
    "",
    "    public static double AverageRating(string clubId)",
    "    {",
    "        var seeds = StartersFor(clubId);",
    "        if (seeds.Length == 0) return 0;",
    "        return seeds.Sum(seed => (double)seed.Rating) / seeds.Length;",
    "    }",
    "",
    "    public static int RoundedRating(string clubId) => (int)Math.Round(AverageRating(clubId), MidpointRounding.AwayFromZero);",
    "}",
    "",
    "public static class ClubDatabase",
    "{",
    "    public static readonly Club[] All =",
    "    [",
]
for club_id, name, short_name, code, country, primary, secondary, _ in clubs:
    lines.append(
        f"        new({cs(club_id)}, {cs(name)}, {cs(short_name)}, {cs(code)}, {cs(country)}, "
        f"{cs(primary)}, {cs(secondary)}, ClubSquads.RoundedRating({cs(club_id)})),"
    )
lines += [
    "    ];",
    "",
    "    public static Club? Club(string? id) =>",
    "        id is null ? null : Array.Find(All, club => club.Id == id);",
    "",
    "    public static Club[] SortedByRating => All",
    "        .OrderByDescending(club => club.Rating)",
    "        .ThenBy(club => club.Name, StringComparer.Ordinal)",
    "        .ToArray();",
    "",
    "    public static Club[][] SeededPots",
    "    {",
    "        get",
    "        {",
    "            var sorted = SortedByRating;",
    "            return sorted",
    "                .Select((club, index) => (club, index))",
    "                .GroupBy(entry => entry.index / 9)",
    "                .Select(group => group.Select(entry => entry.club).ToArray())",
    "                .ToArray();",
    "        }",
    "    }",
    "}",
    "",
    "public sealed record NamePool(string[] First, string[] Last);",
    "",
    "public static class NameDatabase",
    "{",
    "    public static readonly Dictionary<string, NamePool> Pools = new()",
    "    {",
]
for code in sorted(pools):
    first, last = pools[code]
    first_literal = ", ".join(cs(value) for value in first)
    last_literal = ", ".join(cs(value) for value in last)
    lines.append(f"        [{cs(code)}] = new(new[] {{ {first_literal} }}, new[] {{ {last_literal} }}),")
lines += [
    "    };",
    "",
    "    public static readonly NamePool Fallback = new(",
    "        new[] { " + ", ".join(cs(value) for value in fallback[0]) + " },",
    "        new[] { " + ", ".join(cs(value) for value in fallback[1]) + " });",
    "",
    "    public static NamePool Pool(string code) => Pools.TryGetValue(code, out var pool) ? pool : Fallback;",
    "}",
    "",
]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT} ({len(lines)} lines, {len(clubs)} clubs, {len(nations)} nations, {len(pools)} name pools)")
